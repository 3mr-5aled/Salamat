// @desc    Create a doctor
// @route   POST /api/doctors
// @access  Private (Admin only)
exports.createDoctor = asyncHandler(async (req, res, next) => {
  let {
    fullName,
    email,
    password,
    phone,
    gender,
    dateOfBirth,
    specialization,
    clinic,
    qualifications,
    yearsOfExperience,
    availability,
  } = req.body;

  let isAutoGenerated = false;
  if (!password) {
    password = `Sal@${Math.floor(1000 + Math.random() * 9000)}`;
    isAutoGenerated = true;
  }

  const cleanPhone = phone ? phone.replace(/^(\+2|002)/, "").replace(/\s/g, "") : undefined;

  // 1- Create base user first (verified by default when created by admin)
  const user = await User.create({
    name: fullName,
    email,
    password, // Hashed in pre-save middleware
    phone: cleanPhone,
    role: "doctor",
    isVerified: true,
  });

  // 2- Create doctor profile
  const newDoctor = await Doctor.create({
    user: user._id,
    fullName,
    slug: slugify(fullName, { lower: true }),
    gender,
    dateOfBirth,
    specialization,
    clinic,
    qualifications,
    yearsOfExperience,
    availability,
  });

  // Email the credentials if password was auto-generated
  if (isAutoGenerated && email) {
    const message = `Dear Dr. ${fullName},\n\nYour Salamat doctor account has been created by the administrator.\n\nHere are your login credentials:\nEmail: ${email}\nTemporary Password: ${password}\n\nPlease login and change your password immediately.\n\nBest regards,\nThe Salamat Team`;
    try {
      await sendEmail({
        email,
        subject: "Your Salamat Health Portal account credentials",
        message,
      });
    } catch (err) {
      logger.error(`Failed to send credentials email to doctor ${email}:`, err);
      // Dev fallback
      logger.info(`[Doctor Credentials Fallback] Email: ${email} | Password: ${password}`);
    }
  }

  res.status(201).json({
    status: "success",
    message: isAutoGenerated 
      ? `Doctor created successfully. Credentials have been emailed to ${email}.`
      : "Doctor profile and account created successfully.",
    data: newDoctor,
  });
});

// @desc    Update a doctor
// @route   PUT /api/doctors/:id
// @access  Public
exports.updateDoctor = asyncHandler(async (req, res, next) => {
  const doctor = await Doctor.findById(req.params.id);
  if (!doctor) {
    return next(new ApiError(`No doctor for this id ${req.params.id}`, 404));
  }

  // Update associated user if user fields are updated
  const userUpdates = {};
  if (req.body.fullName) userUpdates.name = req.body.fullName;
  if (req.body.email) userUpdates.email = req.body.email;
  if (req.body.phone) {
    userUpdates.phone = req.body.phone.replace(/^(\+2|002)/, "").replace(/\s/g, "");
  }
  if (req.body.password) userUpdates.password = req.body.password;

  if (Object.keys(userUpdates).length > 0 && doctor.user) {
    const userDoc = await User.findById(doctor.user);
    if (userDoc) {
      Object.assign(userDoc, userUpdates);
      await userDoc.save();
    }
  }

  // Update doctor profile
  if (req.body.fullName) {
    req.body.slug = slugify(req.body.fullName, { lower: true });
  }

  const updatedDoctor = await Doctor.findByIdAndUpdate(req.params.id, req.body, {
    new: true,
    runValidators: true,
  });

  // Trigger save middleware/init post events if needed
  if (updatedDoctor) {
    await updatedDoctor.save();
  }

  res.status(200).json({ data: updatedDoctor });
});


