const slugify = require("slugify");
const asyncHandler = require("express-async-handler");
const {
  uploadSingleImage,
  resizeImages,
} = require("../middlewares/uploadImage.middleware");
const Doctor = require("../models/doctor.model");
const User = require("../models/user.model");
const factory = require("./handlers.factory");
const { ApiError, emailUtils, logger } = require("../utils");
const { sendEmail } = emailUtils;

// Upload single image
exports.uploadDoctorImage = uploadSingleImage("profileImg");

exports.resizeImage = resizeImages({
  fieldName: "profileImg",
  uploadPath: "user",
  mimetype: "jpeg",
  quality: 95,
  imageLength: 600,
  imageWidth: 600,
});

// @desc    Get all doctors
// @route   GET /api/doctors
// @access  Public
exports.getAllDoctors = factory.getAll(Doctor, "Doctors", "clinic");

// @desc    Get doctor by ID
// @route   GET /api/doctors/:id
// @access  Public
exports.getDoctorById = factory.getOne(Doctor, "clinic");

// @desc    Create a doctor
// @route   POST /api/doctors
// @access  Private (Admin only)
exports.createDoctor = asyncHandler(async (req, res, next) => {
  let {
    fullName,
    email,
    password,
    phone,
    gender,
    dateOfBirth,
    specialization,
    clinic,
    qualifications,
    yearsOfExperience,
    availability,
  } = req.body;

  let isAutoGenerated = false;
  if (!password) {
    password = `Sal@${Math.floor(1000 + Math.random() * 9000)}`;
    isAutoGenerated = true;
  }

  const cleanPhone = phone ? phone.replace(/^(\+2|002)/, "").replace(/\s/g, "") : undefined;

  // 1- Create base user first (verified by default when created by admin)
  const user = await User.create({
    name: fullName,
    email,
    password, // Hashed in pre-save middleware
    phone: cleanPhone,
    role: "doctor",
    isVerified: true,
  });

  // 2- Create doctor profile
  const newDoctor = await Doctor.create({
    user: user._id,
    fullName,
    slug: slugify(fullName, { lower: true }),
    gender,
    dateOfBirth,
    specialization,
    clinic,
    qualifications,
    yearsOfExperience,
    availability,
  });

  // Email the credentials if password was auto-generated
  if (isAutoGenerated && email) {
    const message = `Dear Dr. ${fullName},\n\nYour Salamat doctor account has been created by the administrator.\n\nHere are your login credentials:\nEmail: ${email}\nTemporary Password: ${password}\n\nPlease login and change your password immediately.\n\nBest regards,\nThe Salamat Team`;
    try {
      await sendEmail({
        email,
        subject: "Your Salamat Health Portal account credentials",
        message,
      });
    } catch (err) {
      logger.error(`Failed to send credentials email to doctor ${email}:`, err);
      // Dev fallback
      logger.info(`[Doctor Credentials Fallback] Email: ${email} | Password: ${password}`);
    }
  }

  res.status(201).json({
    status: "success",
    message: isAutoGenerated 
      ? `Doctor created successfully. Credentials have been emailed to ${email}.`
      : "Doctor profile and account created successfully.",
    data: newDoctor,
  });
});

// @desc    Update a doctor
// @route   PUT /api/doctors/:id
// @access  Public
exports.updateDoctor = factory.updateOne(Doctor);

// @desc    Delete a doctor
// @route   DELETE /api/doctors/:id
// @access  Public
exports.deleteDoctor = factory.deleteOne(Doctor);
